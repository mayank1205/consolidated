def average(a, b):
    return (a + b) / 2

def average(a, b, c = 0):
    return (a + b + c) / 3

# Example usage:
result = average(10, 20)
result1 = average(15, 25)
result2= average(11, 28)
result3 = average(10, 20, 30)
result4 = average(15, 25, 35)
result5 = average(11, 28, 39)
print(result)
print(result1)
print(result2)
print(result3)
print(result4)

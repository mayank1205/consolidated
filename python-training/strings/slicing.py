name = "mayankjoshi"

#positive index
print(name[0:5])

#negative index
print(name[0:-5])

#slicing with step
print(name[0:11:2]) #skipping 1 (n-1) character where n is 2
print(name[0:11:1]) #skipping 0 (n-1) character where n is 1

print(name[:4]) #from start to 4th index
print(name[4:]) #from 4th index to end
